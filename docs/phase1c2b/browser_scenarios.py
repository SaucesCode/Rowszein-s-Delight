"""Real browser assertions for 20/21/25 boundary workflows."""
import re
from urllib.parse import urlsplit
from playwright.sync_api import expect, Error


def verify(page, count, *, go, nav, check, shot, login, logout, edit, db, fault, wait_held, release, result):
    from products.models import Product, Category
    from django.utils import timezone
    last_product=f'Cache product {count:02d}'
    menu=page.locator('#menu')
    def menu_count(): return menu.get_by_text(re.compile(r'^Cache product \d\d$')).count()
    def stock_row(name): return page.get_by_role('row').get_by_text(name,exact=True)
    def lookup(label, term, field, option):
        page.get_by_role('searchbox',name=label+' search',exact=True).fill(term)
        select=page.locator(f'select[name="{field}"]')
        expect(select.locator('option').filter(has_text=option)).to_have_count(1)
        select.select_option(label=option)
        return select.input_value()
    def api(path):
        return page.evaluate('async path=> (await (await fetch(path,{credentials:"same-origin"})).json()).data',path)
    def response(method, path):
        return page.expect_response(lambda r: r.request.method==method and urlsplit(r.url).path==path)
    go('/')
    expect(menu.get_by_text('Cache product 01',exact=True)).to_be_visible()
    check('storefront_initial_bounded_20',menu_count(),20)
    expect(page.locator('#bestsellers').get_by_text(last_product,exact=True)).to_be_visible()
    check('featured_last_product_visible_independently',page.locator('#bestsellers').get_by_text(last_product,exact=True).count(),1)
    more=page.get_by_role('button',name='Load more products',exact=True)
    check('boundary_has_next_only_above_20',more.count(),int(count>20))
    if count>20:
        check('last_product_not_in_first_menu_page',menu.get_by_text(last_product,exact=True).count(),0)
        more.click()
        expect(menu.get_by_text(last_product,exact=True)).to_be_visible()
    check('all_menu_records_once_after_paging',menu_count(),count)
    expect(page.get_by_text('No more products.',exact=True)).to_be_visible()
    shot(f'boundary-{count}-storefront')
    page.get_by_role('searchbox',name='Search menu',exact=True).fill(last_product)
    expect(menu.get_by_text(last_product,exact=True)).to_be_visible()
    expect(menu.get_by_text(re.compile(r'^Cache product \d\d$'))).to_have_count(1)
    check('storefront_search_resets_accumulated_pages',menu_count(),1)
    page.get_by_role('searchbox',name='Search menu',exact=True).fill('unmatched-xyz')
    expect(page.get_by_text('No matching products.',exact=True)).to_be_visible()
    check('storefront_no_match_state',menu_count(),0)
    if count==21:
        page.get_by_role('searchbox',name='Search menu',exact=True).fill('')
        page.get_by_role('searchbox',name='Filter menu by category search',exact=True).fill('Cache category 21')
        page.get_by_role('combobox',name='Filter menu by category',exact=True).select_option(label='Cache category 21')
        expect(menu.get_by_text(last_product,exact=True)).to_be_visible()
        check('later_category_filter_replaces_menu_pages',menu_count(),1)
    login()
    if count==21:
        start=len(result['requests'])
        go('/')
        expect(menu.get_by_text('Cache product 01',exact=True)).to_be_visible()
        public=[row for row in result['requests'][start:] if row['path'].startswith(('/api/products/?','/api/products/categories/?')) and row['status']==200]
        check('owner_storefront_uses_only_public_projection',bool(public) and all('created_at' not in row.get('fields',[]) and 'product_count' not in row.get('fields',[]) for row in public),True)
    go('/sales/new')
    page.get_by_role('button',name='Add Item',exact=True).click()
    sales_product=page.locator('select[name="sale_items.0.product"]')
    expect(sales_product.locator('option')).to_have_count(21)
    check('sales_lookup_initial_page_limit',sales_product.locator('option').count(),21)
    if count>20:
        page.get_by_role('button',name='Product for item 1: load more',exact=True).click()
        expect(sales_product.locator('option')).to_have_count(count+1)
        check('incremental_lookup_no_duplicate_options',sales_product.locator('option').count(),count+1)
    check('sales_lookup_finds_last_id',lookup('Product for item 1',last_product,'sale_items.0.product',last_product),str(count))
    check('new_sale_price_uses_selected_product',page.locator('input[name="sale_items.0.unit_price"]').input_value(),'50')
    shot(f'boundary-{count}-sale-lookup')
    if count==20:
        # Create the only row on page 2, update it, then delete it while on that page.
        go('/ingredients/new')
        page.locator('input[name="name"]').fill('ZZZ boundary fixture')
        page.locator('input[name="quantity"]').fill('0')
        page.locator('select[name="unit"]').select_option('kg')
        page.locator('input[name="cost_per_unit"]').fill('1')
        page.locator('input[name="minimum_stock"]').fill('0')
        with response('POST','/api/ingredients/') as saved:
            page.get_by_role('button',name='Add Ingredient',exact=True).click()
        check('create_moves_count_20_to_21',saved.value.status,201)
        pk=saved.value.json()['data']['id']
        page.wait_for_url('**/ingredients')
        page.get_by_role('button',name='Next page',exact=True).click()
        expect(stock_row('ZZZ boundary fixture')).to_be_visible()
        edit('ZZZ boundary fixture')
        page.locator('input[name="name"]').fill('ZZZ boundary updated')
        with response('PUT',f'/api/ingredients/{pk}/') as saved:
            page.get_by_role('button',name='Update Ingredient',exact=True).click()
        check('edit_refreshes_paged_list',saved.value.status,200)
        page.wait_for_url('**/ingredients')
        page.get_by_role('button',name='Next page',exact=True).click()
        expect(stock_row('ZZZ boundary updated')).to_be_visible()
        page.get_by_role('button',name='Actions for ZZZ boundary updated',exact=True).click()
        page.get_by_role('button',name='Delete',exact=True).click()
        with response('DELETE',f'/api/ingredients/{pk}/') as saved:
            page.get_by_role('alertdialog').get_by_role('button',name='Delete',exact=True).click()
        check('delete_only_row_on_last_page',saved.value.status,200)
        expect(stock_row('Cache ingredient 01')).to_be_visible()
        expect(page.get_by_role('button',name='Next page',exact=True)).to_have_count(0)
        check('page_recovers_after_delete',stock_row('Cache ingredient 01').count(),1)
        shot('boundary-20-after-delete')
    if count!=25:
        check('no_page_errors',result['page_errors'],[])
        return
    go('/ingredients')
    edit('Cache ingredient 01')
    expect(page.locator('input[name="name"]')).to_have_value('Cache ingredient 01')
    check('f04_ingredient_page1_id1',page.locator('input[name="name"]').input_value(),'Cache ingredient 01')
    nav('/ingredients')
    page.get_by_role('button',name='Next page',exact=True).click()
    edit('Z Cache ingredient 02')
    expect(page.locator('input[name="name"]')).to_have_value('Z Cache ingredient 02')
    check('f04_ingredient_page2_id2',page.locator('input[name="name"]').input_value(),'Z Cache ingredient 02')
    nav('/ingredients')
    page.get_by_role('button',name='Next page',exact=True).click()
    search=page.get_by_role('textbox',name='Search ingredients')
    search.fill('Cache ingredient 25')
    expect(stock_row('Cache ingredient 25')).to_be_visible()
    check('management_search_resets_page',page.get_by_role('button',name='Next page',exact=True).count(),0)
    fault.update(path='/api/ingredients/?search=Cache+ingredient+01&ordering=name&page=1',mode='hold')
    search.fill('Cache ingredient 01')
    wait_held()
    search.fill('Cache ingredient 24')
    expect(stock_row('Cache ingredient 24')).to_be_visible()
    try: release()
    except Error as error:
        result['late_request_release']=str(error)
        fault['held'].clear()
    expect(stock_row('Cache ingredient 01')).to_have_count(0)
    check('late_response_never_overwrites_new_search',stock_row('Cache ingredient 24').count(),1)
    go('/recipes')
    edit('Cache product 01 recipe')
    expect(page.locator('select[name="product"]')).to_have_value('1')
    check('f04_recipe_page1_id1',page.locator('select[name="product"]').input_value(),'1')
    nav('/recipes')
    page.get_by_role('textbox',name='Search recipes').fill('Cache product 25')
    expect(page.get_by_role('row').filter(has_text=last_product)).to_contain_text('Cache category 25')
    check('recipe_search_returns_off_page_category',page.get_by_role('row').filter(has_text=last_product).count(),1)
    edit('Cache product 25 recipe')
    expect(page.locator('select[name="product"]')).to_have_value('25')
    expect(page.locator('select[name="recipe_ingredients.0.ingredient"]')).to_have_value('25')
    check('off_page_recipe_product_retained',page.locator('select[name="product"]').input_value(),'25')
    check('off_page_recipe_ingredient_retained',page.locator('select[name="recipe_ingredients.0.ingredient"]').input_value(),'25')
    shot('recipe-edit-off-page')
    go('/recipes/new')
    page.get_by_role('button',name='Add Row',exact=True).click()
    check('recipe_lookup_finds_ingredient25',lookup('Ingredient 1','Cache ingredient 25','recipe_ingredients.0.ingredient','Cache ingredient 25'),'25')
    go('/products/25/edit')
    category_id=str(api('/api/products/25/')['category']['id'])
    expect(page.locator('select[name="category_id"]')).to_have_value(category_id)
    check('off_page_edit_category_retained',page.locator('select[name="category_id"]').input_value(),category_id)
    go('/products/new')
    check('category_lookup_finds_later_category',lookup('Category','Cache category 25','category_id','Cache category 25'),category_id)
    go('/products')
    page.get_by_role('textbox',name='Search products').fill('Cache product 01')
    expect(page.get_by_text('Cache product 01',exact=True).first).to_be_visible()
    check('product_management_search_finds_later_row',page.get_by_text('Cache product 01',exact=True).count()>0,True)
    # Real synthetic sale at an owner-entered historical price. Lookup pinning
    # must never reprice it to the current catalog price (50).
    sale=page.evaluate('''async day=>{const csrf=await (await fetch('/api/auth/csrf/')).json();
      const r=await fetch('/api/sales/',{method:'POST',headers:{'Content-Type':'application/json','X-CSRFToken':csrf.data.csrf_token,'Idempotency-Key':crypto.randomUUID()},
      body:JSON.stringify({date:day,sale_items:[{product:25,quantity:1,unit_price:'31.00'}]})});return {status:r.status,body:await r.json()};}''',db(timezone.localdate).isoformat())
    check('synthetic_sale_with_historical_price_created',sale['status'],201)
    go(f"/sales/{sale['body']['data']['id']}/edit")
    expect(page.locator('select[name="sale_items.0.product"]')).to_have_value('25')
    check('off_page_sale_product_retained',page.locator('select[name="sale_items.0.product"]').input_value(),'25')
    check('sale_lookup_does_not_reprice_history',page.locator('input[name="sale_items.0.unit_price"]').input_value(),'31')
    logout();login('staff','staff',direct=False)
    nav('/ingredients')
    page.get_by_role('textbox',name='Search stock').fill('Cache ingredient 25')
    expect(page.get_by_text('Cache ingredient 25',exact=True)).to_be_visible()
    stock=api('/api/ingredients/?search=Cache+ingredient+25')['results'][0]
    check('staff_lookup_projects_only_operational_fields',sorted(stock),['id','is_low_stock','name','quantity','unit'])
    check('staff_no_owner_supplier_dom','PRIVATE-SUPPLIER' in page.locator('body').inner_text(),False)
    go('/sales/new')
    page.get_by_role('button',name='Add Item',exact=True).click()
    check('staff_sale_lookup_finds_later_product',lookup('Product for item 1',last_product,'sale_items.0.product',last_product),'25')
    logout()
    db(lambda:Product.objects.filter(pk=25).update(is_available=False))
    db(lambda:Category.objects.filter(name='Cache category 24').update(is_active=False))
    go('/')
    expect(menu.get_by_text('Cache product 01',exact=True)).to_be_visible()
    more.click()
    expect(page.get_by_text('No more products.',exact=True)).to_be_visible()
    check('public_excludes_hidden_and_inactive_category',menu_count(),23)
    check('public_hidden_featured_absent',page.locator('#bestsellers').count(),0)
    check('no_page_errors',result['page_errors'],[])
